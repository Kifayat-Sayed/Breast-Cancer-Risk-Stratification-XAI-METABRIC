# ---------------------------------------------------------------------------
# Helper function for threshold-based evaluation
# ---------------------------------------------------------------------------

def evaluate_threshold(y_true, probabilities, threshold):

    predictions = (
        probabilities >= threshold
    ).astype(int)

    tn, fp, fn, tp = confusion_matrix(
        y_true,
        predictions,
        labels=[0, 1]
    ).ravel()

    recall = recall_score(
        y_true,
        predictions,
        zero_division=0
    )

    precision = precision_score(
        y_true,
        predictions,
        zero_division=0
    )

    specificity = (
        tn / (tn + fp)
        if (tn + fp) > 0
        else 0.0
    )

    npv = (
        tn / (tn + fn)
        if (tn + fn) > 0
        else 0.0
    )

    f1 = f1_score(
        y_true,
        predictions,
        zero_division=0
    )

    f2 = fbeta_score(
        y_true,
        predictions,
        beta=2,
        zero_division=0
    )

    balanced_accuracy = balanced_accuracy_score(
        y_true,
        predictions
    )

    mcc = matthews_corrcoef(
        y_true,
        predictions
    )

    return {
        "Threshold": threshold,
        "TN": tn,
        "FP": fp,
        "FN": fn,
        "TP": tp,
        "Recall": recall,
        "Specificity": specificity,
        "Precision": precision,
        "NPV": npv,
        "F1": f1,
        "F2": f2,
        "Balanced Accuracy": balanced_accuracy,
        "MCC": mcc
    }


